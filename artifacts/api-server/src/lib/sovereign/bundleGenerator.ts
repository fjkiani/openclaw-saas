/**
 * bundleGenerator.ts — sovereign (on-prem / air-gapped) deployment bundle generator.
 *
 * Generates a complete, self-contained deployment package a tenant can run in
 * their own environment (VPC, on-prem, isolated tenant) with NO public-cloud
 * dependency: local Postgres, local Qdrant, locally-hosted LLM (Ollama), the
 * OpenClaw API, and the front-end — wired together with local auth.
 *
 * This is the V2 moat: a hedge fund / hospital / compliance-bound tenant gets
 * the full platform inside their perimeter, driven from the front-end.
 *
 * Output: a set of files (compose, env template, Dockerfiles, scripts, README)
 * returned as a map { path -> content } and packaged as a tarball by the route.
 */

export interface SovereignConfig {
  tenantName: string;          // e.g. "acme-capital"
  domain?: string;             // e.g. "openclaw.acme.internal" (optional; default localhost)
  llmBackend: "local" | "hybrid";  // local = fully air-gapped; hybrid = local-first + cloud fallback
  localChatModel: string;      // e.g. "llama3.1:8b"
  localEmbedModel: string;     // e.g. "nomic-embed-text"
  authProvider: "local";       // sovereign always uses local auth (no Clerk)
  apiPort: number;             // default 3001
  webPort: number;             // default 8080
  enableGpu: boolean;          // pass GPU to Ollama
}

export interface BundleFile {
  path: string;
  content: string;
  executable?: boolean;
}

export function defaultSovereignConfig(tenantName: string): SovereignConfig {
  return {
    tenantName: tenantName.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "") || "tenant",
    domain: "localhost",
    llmBackend: "local",
    localChatModel: "llama3.1:8b",
    localEmbedModel: "nomic-embed-text",
    authProvider: "local",
    apiPort: 3001,
    webPort: 8080,
    enableGpu: false,
  };
}


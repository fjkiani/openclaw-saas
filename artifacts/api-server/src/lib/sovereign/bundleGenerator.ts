export function generateSovereignBundle(config: Partial<SovereignConfig> & { tenantName: string }): BundleFile[] {
  const c: SovereignConfig = { ...defaultSovereignConfig(config.tenantName), ...config };
  return [
    { path: "docker-compose.yml", content: dockerCompose(c) },
    { path: "env.template", content: envTemplate(c) },
    { path: "api/Dockerfile", content: apiDockerfile() },
    { path: "web/Dockerfile", content: webDockerfile() },
    { path: "web/nginx.conf", content: nginxConf() },
    { path: "setup.sh", content: setupScript(c), executable: true },
    { path: "backup.sh", content: backupScript(), executable: true },
    { path: "README.md", content: readme(c) },
  ];
}
